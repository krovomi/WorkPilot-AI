/**
 * @vitest-environment node
 *
 * Posting an AI review to a stand-in GitHub: the body built from the chosen
 * findings, the verdict they give, and the fall back to a comment on the
 * person's own PR, where GitHub refuses an approval or a change request.
 */

import { beforeEach, describe, expect, it, vi } from "vitest";

const state = vi.hoisted(() => ({
	posts: [] as { endpoint: string; body: { body: string; event: string } }[],
	refusals: [] as unknown[],
	answer: undefined as unknown,
}));

vi.mock("../utils", () => ({
	githubFetch: async (_token: string, endpoint: string, options: RequestInit) => {
		const body = JSON.parse(String(options.body));
		state.posts.push({ endpoint, body });
		const refusal = state.refusals.shift();
		if (refusal !== undefined) throw refusal;
		return state.answer ?? { id: 900 + state.posts.length };
	},
}));

import { postReviewToGitHub } from "../pr-review-post";
import type { PRReviewFinding, PRReviewResult } from "../review-result";

const config = { token: "pat-test-0000", repo: "acme/shop" };
const finding = (id: string, severity: string, extra: Partial<PRReviewFinding> = {}) =>
	({
		id,
		severity,
		category: "quality",
		title: `Title ${id}`,
		description: `Description ${id}`,
		file: "src/a.ts",
		line: 3,
		...extra,
	}) as PRReviewFinding;
const result = (findings: PRReviewFinding[], overallStatus: PRReviewResult["overallStatus"] = "comment") =>
	({ prNumber: 7, summary: "Two issues", findings, overallStatus }) as PRReviewResult;

beforeEach(() => {
	state.posts = [];
	state.refusals = [];
	state.answer = undefined;
});

describe("postReviewToGitHub", () => {
	it("posts every finding with the review's own verdict when none is chosen", async () => {
		const findings = [
			finding("f-1", "high", { suggestedFix: "  use a guard  " }),
			finding("f-2", "low", { suggestedFix: "   " }),
			finding("f-3", "unknown"),
		];

		await expect(postReviewToGitHub(config, 7, result(findings, "request_changes"))).resolves.toEqual({
			reviewId: 901,
			findings,
		});

		const [{ endpoint, body }] = state.posts;
		expect(endpoint).toBe("/repos/acme/shop/pulls/7/reviews");
		expect(body.event).toBe("REQUEST_CHANGES");
		expect(body.body).toContain("## 🤖 WorkPilot AI PR Review\n\nTwo issues");
		expect(body.body).toContain("### Findings (3 total)");
		expect(body.body).toContain("#### 🟠 [f-1] [HIGH] Title f-1\n📁 `src/a.ts:3`\n\nDescription f-1");
		expect(body.body).toContain("**Suggested fix:**\n```\nuse a guard\n```");
		expect(body.body).toContain("#### 🔵 [f-2] [LOW]");
		expect(body.body).toContain("#### ⚪ [f-3] [UNKNOWN]");
		expect(body.body.match(/Suggested fix/g)).toHaveLength(1);
		expect(body.body).toMatch(/generated by WorkPilot AI\.\*$/);
	});

	it.each([
		[["f-1"], "REQUEST_CHANGES", "1 selected of 3 total"],
		[["f-2"], "REQUEST_CHANGES", "1 selected of 3 total"],
		[["f-3"], "COMMENT", "1 selected of 3 total"],
		[[], "APPROVE", null],
	])("gives the verdict of the chosen findings %j", async (ids, event, count) => {
		const findings = [finding("f-1", "critical"), finding("f-2", "high"), finding("f-3", "medium")];

		const posted = await postReviewToGitHub(config, 7, result(findings, "comment"), ids);

		expect(posted.findings.map((f) => f.id)).toEqual(ids);
		expect(state.posts[0].body.event).toBe(event);
		if (count) expect(state.posts[0].body.body).toContain(`### Findings (${count})`);
		else expect(state.posts[0].body.body).toContain("*No findings selected for this review.*");
	});

	it.each([
		["approve", "APPROVE"],
		["comment", "COMMENT"],
	] as const)("keeps the review's verdict %s without a selection", async (status, event) => {
		await postReviewToGitHub(config, 7, result([], status));

		expect(state.posts[0].body.event).toBe(event);
	});

	it("approves anyway, with the findings as suggestions", async () => {
		const findings = [finding("f-1", "critical", { suggestedFix: "fix" }), finding("f-2", "medium")];

		await postReviewToGitHub(config, 7, result(findings, "request_changes"), undefined, { forceApprove: true });

		const { body } = state.posts[0];
		expect(body.event).toBe("APPROVE");
		expect(body.body).toContain("## ✅ WorkPilot AI Review - APPROVED");
		expect(body.body).toContain("**Summary:** Two issues");
		expect(body.body).toContain("### 💡 Suggestions (2)");
		expect(body.body).toContain("#### 🔴 [f-1] [CRITICAL]");
		expect(body.body).toContain("#### 🟡 [f-2] [MEDIUM]");
		expect(body.body).toContain("**Suggested fix:**\n```\nfix\n```");
	});

	it("approves anyway without a suggestions section when nothing is chosen", async () => {
		await postReviewToGitHub(config, 7, result([finding("f-1", "high")]), [], { forceApprove: true });

		expect(state.posts[0].body.body).not.toContain("Suggestions");
		expect(state.posts[0].body.body).toContain("The PR can be safely merged.");
	});

	it.each([
		new Error("Can not request changes on your own pull request"),
		new Error("Unprocessable: Can not approve your own pull request"),
		"Can not approve your own pull request",
	])("comments instead on the person's own PR (%s)", async (refusal) => {
		state.refusals = [refusal];

		const posted = await postReviewToGitHub(config, 7, result([finding("f-1", "high")], "request_changes"));

		expect(state.posts.map((p) => p.body.event)).toEqual(["REQUEST_CHANGES", "COMMENT"]);
		expect(state.posts[1].body.body).toBe(state.posts[0].body.body);
		expect(posted.reviewId).toBe(902);
	});

	it("fails with any other refusal", async () => {
		state.refusals = [new Error("HTTP 422 Validation Failed")];

		await expect(postReviewToGitHub(config, 7, result([]))).rejects.toThrow("HTTP 422");
		expect(state.posts).toHaveLength(1);
	});

	it("fails when GitHub answers without the review's id, so nothing records a review that is not there", async () => {
		for (const answer of [{}, { id: "901" }, { id: 0 }, { id: 1.5 }, { id: null }]) {
			state.answer = answer;
			await expect(postReviewToGitHub(config, 7, result([]))).rejects.toThrow(
				"GitHub did not return the review's id",
			);
		}
	});
});
