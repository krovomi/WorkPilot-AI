/**
 * `.workpilot/review-conventions.md`, written on request from the project's
 * feedback on PR review findings (#361, lot 2).
 *
 * The rules are deduced from the dataset, without a model: what the reviewer
 * drops, what it raises as low only, what the project keeps accepting, and
 * what is never touched. The same dataset always gives the same file (no
 * date, a stable order), so it can be committed and reviewed like any other.
 *
 * A finding title is model output written while reading a pull request: in
 * the file it is one bounded line, its Markdown and HTML characters escaped,
 * so it cannot add a link, a heading or markup. The file is written inside
 * the project, refused when it is a link (`writableFileUnder`), through a
 * temporary file renamed over it. A server project's file is built from the
 * server's dataset and saved where the person chooses (`saveConventionsAs`).
 */

import { randomUUID } from "node:crypto";
import { mkdirSync, renameSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import type {
	ReviewConventionsResult,
	ReviewFeedbackReason,
} from "../../../shared/types/review-feedback";
import {
	displayLabel,
	type FeedbackRecord,
	net,
	rejections,
	tallyBySignature,
	topReason,
} from "./review-feedback-dataset";
import { showSaveDialog } from "../../electron-utils";
import { learnedRules } from "./review-feedback-stats";
import { readRecords, writableFileUnder } from "./review-feedback-store";

export const CONVENTIONS_RELATIVE_PATH = path.join(
	".workpilot",
	"review-conventions.md",
);

const REASON_LABELS: Record<ReviewFeedbackReason, string> = {
	too_pedantic: "too pedantic",
	project_convention: "the project's convention differs",
	false_positive: "false positive",
	legacy_exception: "legacy code exception",
	other: "other",
};

/** One line of Markdown text that renders as itself. */
export function escapeInline(text: string): string {
	return displayLabel(text).replace(/[\\`*_[\]<>|#!~&]/g, (char) => `\\${char}`);
}

function ruleLine(
	category: string,
	label: string,
	rejected: number,
	accepted: number,
	reason: ReviewFeedbackReason | null,
): string {
	const why = reason ? `; mostly: ${REASON_LABELS[reason]}` : "";
	return `- **${escapeInline(category)}**: ${escapeInline(label)} (rejected ${rejected}, accepted ${accepted}${why})`;
}

function section(title: string, intro: string, lines: string[]): string[] {
	return [`## ${title}`, "", intro, "", ...(lines.length ? lines : ["None yet."]), ""];
}

/** A stable order: by category, then by signature. */
function byCategory(
	a: { category: string; signature: string },
	b: { category: string; signature: string },
): number {
	return (
		a.category.localeCompare(b.category, "en") ||
		a.signature.localeCompare(b.signature, "en")
	);
}

export function buildConventions(
	records: readonly FeedbackRecord[],
	threshold: number,
): { markdown: string; rules: number } {
	const tallies = tallyBySignature(records);
	const learned = learnedRules(records, threshold).sort(byCategory);
	const line = (rule: (typeof learned)[number]) =>
		ruleLine(rule.category, rule.label, rule.rejections, rule.accepts, rule.topReason);
	const dropped = learned.filter((rule) => rule.status === "dropped").map(line);
	const downgraded = learned
		.filter((rule) => rule.status === "downgraded")
		.map(line);
	const kept = [...tallies.values()]
		.filter((tally) => -net(tally) >= threshold)
		.sort(byCategory)
		.map((tally) =>
			ruleLine(
				tally.category,
				tally.title,
				rejections(tally),
				tally.accepted,
				topReason(tally),
			),
		);

	const markdown = [
		"# Review conventions",
		"",
		"<!-- Generated by WorkPilot AI from .workpilot/code_review_feedback.jsonl. " +
			"Regenerate it from the PR review view rather than editing it. -->",
		"",
		`Deduced from ${records.length} verdict(s) on ${tallies.size} kind(s) of review remark. ` +
			`A kind of remark is its category and its title with names and numbers taken out. ` +
			`Threshold: ${threshold} more rejections than acceptances.`,
		"",
		...section(
			"Not raised on this project",
			`Rejected at least ${2 * threshold} times more than accepted: the reviewer drops them and lists them as hidden.`,
			dropped,
		),
		...section(
			"Raised as low only",
			`Rejected at least ${threshold} times more than accepted: the reviewer keeps them, downgraded to low.`,
			downgraded,
		),
		...section(
			"Kept: remarks this project accepts",
			`Accepted at least ${threshold} times more than rejected.`,
			kept,
		),
		"## Always reviewed",
		"",
		"Security findings and critical findings are never downgraded or dropped, whatever the feedback says.",
	].join("\n");
	return {
		markdown: `${markdown}\n`,
		rules: dropped.length + downgraded.length + kept.length,
	};
}

/** Write `markdown` to `file` at once; false when it could not be. */
function replaceWith(file: string, markdown: string): boolean {
	// A fresh name, created exclusively: never through a file or link already there.
	const temp = `${file}.${randomUUID()}.tmp`;
	try {
		mkdirSync(path.dirname(file), { recursive: true });
		writeFileSync(temp, markdown, { encoding: "utf-8", flag: "wx" });
		renameSync(temp, file);
	} catch {
		rmSync(temp, { force: true });
		return false;
	}
	return true;
}

/** Write the file in the project; the path in the answer is relative to it. */
export function writeConventions(
	projectPath: string,
	threshold: number,
): ReviewConventionsResult {
	const file = writableFileUnder(projectPath, CONVENTIONS_RELATIVE_PATH);
	if (!file) return { success: false, error: "write_failed" };
	const { markdown, rules } = buildConventions(readRecords(projectPath), threshold);
	if (!replaceWith(file, markdown)) return { success: false, error: "write_failed" };
	return {
		success: true,
		path: CONVENTIONS_RELATIVE_PATH.split(path.sep).join("/"),
		rules,
	};
}

/**
 * A server project's file (lot 4): its clone is nobody's working copy, so the
 * person picks where to save it, in a native dialog, usually their own
 * checkout, to commit it there. The path comes from the dialog, never from
 * the renderer; a link there is refused. The answer names the full path.
 */
export async function saveConventionsAs(
	records: readonly FeedbackRecord[],
	threshold: number,
): Promise<ReviewConventionsResult> {
	const { markdown, rules } = buildConventions(records, threshold);
	const { canceled, filePath } = await showSaveDialog({
		defaultPath: path.basename(CONVENTIONS_RELATIVE_PATH),
		filters: [{ name: "Markdown", extensions: ["md"] }],
	});
	if (canceled || !filePath) return { success: false, error: "cancelled" };
	const file = writableFileUnder(path.dirname(filePath), path.basename(filePath));
	if (!file || !replaceWith(file, markdown)) {
		return { success: false, error: "write_failed" };
	}
	return { success: true, path: file, rules };
}
