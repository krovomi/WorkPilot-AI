/**
 * @vitest-environment node
 *
 * A saved MR review as the runner writes it, read for the view, and the note
 * it posts as on the merge request.
 */

import { describe, expect, it } from "vitest";
import { mrReviewFromJson, mrReviewNote } from "../mr-review-result";
import type { MRReviewResult } from "../types";

describe("reading a saved review", () => {
	it("refuses what is not a review object", () => {
		for (const text of ["null", "[]", "42", '"review"']) {
			expect(() => mrReviewFromJson(text)).toThrow("Not a review");
		}
		expect(() => mrReviewFromJson("{")).toThrow(SyntaxError);
	});

	it("takes the runner's names, and defaults what it left out", () => {
		const review = mrReviewFromJson(
			JSON.stringify({
				mr_iid: 7,
				reviewed_commit_sha: "abc",
				findings: [{ id: "f1", severity: "low", end_line: 4, suggested_fix: "rename" }],
			}),
		);
		expect(review).toMatchObject({
			mrIid: 7,
			reviewedCommitSha: "abc",
			summary: "",
			overallStatus: "comment",
			isFollowupReview: false,
			hasPostedFindings: false,
			postedFindingIds: [],
			findings: [{ id: "f1", endLine: 4, suggestedFix: "rename", fixable: false }],
		});
		expect(Number.isNaN(Date.parse(review.reviewedAt))).toBe(false);
		expect(mrReviewFromJson('{"findings":"none"}').findings).toEqual([]);
	});
});

describe("the note a review posts as", () => {
	const review = {
		summary: "Summary.",
		findings: [
			{ id: "f1", severity: "critical", title: "SQL", description: "built by hand", file: "db.ts", line: 2, suggestedFix: "  use params  " },
			{ id: "f2", severity: "odd", title: "Style", description: "spacing", file: "ui.ts", line: 5, suggestedFix: "   " },
		],
	} as unknown as MRReviewResult;

	it("names every finding, with its fix when it has one", () => {
		const { body, findings } = mrReviewNote(review);
		expect(findings).toHaveLength(2);
		expect(body).toContain("### Findings (2 total)");
		expect(body).toContain("#### 🔴 [CRITICAL] SQL\n📁 `db.ts:2`");
		expect(body).toContain("**Suggested fix:**\n```\nuse params\n```");
		expect(body).toContain("#### ⚪ [ODD] Style");
		expect(body.match(/Suggested fix/g)).toHaveLength(1);
		expect(body.endsWith("*This review was generated by WorkPilot AI.*")).toBe(true);
	});

	it("names only the chosen findings, and says when none is chosen", () => {
		expect(mrReviewNote(review, ["f2"]).body).toContain("### Findings (1 selected of 2 total)");
		const none = mrReviewNote(review, []);
		expect(none.findings).toEqual([]);
		expect(none.body).toContain("*No findings selected for this review.*");
	});
});
