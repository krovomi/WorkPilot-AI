/**
 * A saved MR review, as the GitLab runner writes it
 * (`.workpilot/gitlab/mr/review_<iid>.json`), read for the view, and the
 * note a review is posted as on the merge request. A local project's review
 * is read from its folder (`mr-review-handlers.ts`), a server project's from
 * the server (`server-mr-review.ts`).
 */

import type { MRReviewFinding, MRReviewResult } from "./types";

/** The view's review, from the runner's saved data. */
export function mrReviewFromData(data: Record<string, unknown>): MRReviewResult {
	const findings = Array.isArray(data.findings) ? data.findings : [];
	return {
		mrIid: data.mr_iid,
		project: data.project,
		success: data.success,
		findings: findings.map((f: Record<string, unknown>) => ({
			id: f.id,
			severity: f.severity,
			category: f.category,
			title: f.title,
			description: f.description,
			file: f.file,
			line: f.line,
			endLine: f.end_line,
			suggestedFix: f.suggested_fix,
			fixable: f.fixable ?? false,
		})),
		summary: data.summary ?? "",
		overallStatus: data.overall_status ?? "comment",
		reviewedAt: data.reviewed_at ?? new Date().toISOString(),
		reviewedCommitSha: data.reviewed_commit_sha,
		jev: data.jev,
		isFollowupReview: data.is_followup_review ?? false,
		previousReviewId: data.previous_review_id,
		resolvedFindings: data.resolved_findings ?? [],
		unresolvedFindings: data.unresolved_findings ?? [],
		newFindingsSinceLastReview: data.new_findings_since_last_review ?? [],
		hasPostedFindings: data.has_posted_findings ?? false,
		postedFindingIds: data.posted_finding_ids ?? [],
	} as MRReviewResult;
}

/** The view's review, from the saved file's text; throws when it is not one. */
export function mrReviewFromJson(text: string): MRReviewResult {
	const data: unknown = JSON.parse(text);
	if (!data || typeof data !== "object" || Array.isArray(data)) {
		throw new Error("Not a review");
	}
	return mrReviewFromData(data as Record<string, unknown>);
}

/**
 * The note that posts a review on its merge request, with the findings it
 * names: those selected, or all of them.
 */
export function mrReviewNote(
	result: MRReviewResult,
	selectedFindingIds?: readonly string[],
): { body: string; findings: MRReviewFinding[] } {
	const selectedSet = selectedFindingIds ? new Set(selectedFindingIds) : null;
	const findings = selectedSet
		? result.findings.filter((f) => selectedSet.has(f.id))
		: result.findings;

	let body = `## WorkPilot AI MR Review\n\n${result.summary}\n\n`;
	if (findings.length > 0) {
		const countText = selectedSet
			? `${findings.length} selected of ${result.findings.length} total`
			: `${findings.length} total`;
		body += `### Findings (${countText})\n\n`;
		for (const f of findings) {
			const emoji =
				{ critical: "🔴", high: "🟠", medium: "🟡", low: "🔵" }[f.severity] || "⚪";
			body += `#### ${emoji} [${f.severity.toUpperCase()}] ${f.title}\n`;
			body += `📁 \`${f.file}:${f.line}\`\n\n`;
			body += `${f.description}\n\n`;
			const suggestedFix = f.suggestedFix?.trim();
			if (suggestedFix) {
				body += `**Suggested fix:**\n\`\`\`\n${suggestedFix}\n\`\`\`\n\n`;
			}
		}
	} else {
		body += `*No findings selected for this review.*\n\n`;
	}
	body += `---\n*This review was generated by WorkPilot AI.*`;
	return { body, findings };
}
