#!/usr/bin/env python3
"""Atlas cards of the audit findings that have their own file.

From F113 on, each audit finding is ``docs/audit/findings/F<n>.md``: the
detailed finding, with the fields of its atlas card in the frontmatter. The
atlas (``docs/audit/WorkPilot-architecture.html``) is opened from disk and
cannot read Markdown, so this writes ``F<n>.js`` beside each one, which the
atlas loads. Two PRs that each add a finding then touch different files.

    python scripts/audit_findings.py build   write the .js files, remove orphans
    python scripts/audit_findings.py check   exit 1 if one is missing, stale or invalid
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
FINDINGS_DIR = ROOT / "docs" / "audit" / "findings"
FIRST_FILE_ID = 113
"""The first finding kept in its own file; the atlas starts probing here."""

SEVERITIES = ("crit", "haute", "moy", "basse")
STATUSES = ("nouveau", "aggravé", "ouvert", "partiel", "atténué", "résolu")
CARD_FIELDS = {
    "finding": "c",
    "evidence": "p",
    "recommendation": "r",
    "gain": "g",
    "preserve": "k",
}
FILE_NAME = re.compile(r"^F(\d+)\.md$")
HEADER = "// Generated by scripts/audit_findings.py from {md}: edit the .md, then run build.\n"


class FindingError(ValueError):
    pass


def split_frontmatter(text: str, name: str) -> tuple[dict, str]:
    if not text.startswith("---\n"):
        raise FindingError(f"{name}: no frontmatter")
    end = text.find("\n---\n", 4)
    if end < 0:
        raise FindingError(f"{name}: frontmatter is not closed")
    try:
        meta = yaml.safe_load(text[4:end])
    except yaml.YAMLError as error:
        # Usually a " : " in a plain value: write long fields as `>-` blocks.
        raise FindingError(f"{name}: frontmatter is not valid YAML: {error}") from None
    if not isinstance(meta, dict):
        raise FindingError(f"{name}: frontmatter is not a mapping")
    return meta, text[end + len("\n---\n") :]


def card(path: Path) -> dict[str, str]:
    """The atlas card of one finding file, validated."""
    name = path.name
    match = FILE_NAME.match(name)
    if not match:
        raise FindingError(f"{name}: a finding file is named F<n>.md")
    meta, body = split_frontmatter(path.read_text(encoding="utf-8"), name)
    fid = f"F{match.group(1)}"
    if meta.get("id") != fid:
        raise FindingError(f"{name}: id is {meta.get('id')!r}, expected {fid!r}")
    if meta.get("severity") not in SEVERITIES:
        raise FindingError(f"{name}: severity must be one of {', '.join(SEVERITIES)}")
    if meta.get("status") not in STATUSES:
        raise FindingError(f"{name}: status must be one of {', '.join(STATUSES)}")
    for key in ("title", "category", "verified"):
        if not isinstance(meta.get(key), str) or not meta[key].strip():
            raise FindingError(f"{name}: {key} is missing")
    heading = f"# {fid} · {meta['title']}"
    if body.lstrip("\n").splitlines()[:1] != [heading]:
        raise FindingError(f"{name}: the body starts with {heading!r}")
    fields = meta.get("card")
    if not isinstance(fields, dict) or set(fields) != set(CARD_FIELDS):
        raise FindingError(f"{name}: card has exactly {', '.join(CARD_FIELDS)}")
    out = {
        "id": fid,
        "sev": meta["severity"],
        "cat": meta["category"],
        "st": meta["status"],
        "v": meta["verified"],
        # The atlas prints the title as text: Markdown code spans lose their backticks.
        "t": meta["title"].replace("`", ""),
    }
    for key, short in CARD_FIELDS.items():
        value = fields[key]
        if not isinstance(value, str) or not value.strip():
            raise FindingError(f"{name}: card.{key} is empty")
        out[short] = value.strip()
    return out


def render(path: Path) -> str:
    entry = json.dumps(card(path), ensure_ascii=False)
    return HEADER.format(md=path.name) + f"FINDINGS.push({entry});\n"


def expected_outputs(directory: Path = FINDINGS_DIR) -> dict[Path, str]:
    return {md.with_suffix(".js"): render(md) for md in sorted(directory.glob("F*.md"))}


def problems(directory: Path = FINDINGS_DIR) -> list[str]:
    try:
        wanted = expected_outputs(directory)
    except FindingError as error:
        return [str(error)]
    found = []
    for js, text in wanted.items():
        if not js.exists():
            found.append(f"{js.name} is missing")
        elif js.read_text(encoding="utf-8") != text:
            found.append(f"{js.name} is stale")
    for js in sorted(directory.glob("F*.js")):
        if js not in wanted:
            found.append(f"{js.name} has no {js.with_suffix('.md').name}")
    return found


def build(directory: Path = FINDINGS_DIR) -> None:
    wanted = expected_outputs(directory)
    for js, text in wanted.items():
        if not js.exists() or js.read_text(encoding="utf-8") != text:
            js.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {js.relative_to(ROOT)}")
    for js in sorted(directory.glob("F*.js")):
        if js not in wanted:
            js.unlink()
            print(f"removed {js.relative_to(ROOT)}")


def main(argv: list[str]) -> int:
    command = argv[1] if len(argv) > 1 else "check"
    if command == "build":
        try:
            build()
        except FindingError as error:
            print(error, file=sys.stderr)
            return 1
        return 0
    if command == "check":
        found = problems()
        for problem in found:
            print(problem, file=sys.stderr)
        if found:
            print("run: python scripts/audit_findings.py build", file=sys.stderr)
        return 1 if found else 0
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
